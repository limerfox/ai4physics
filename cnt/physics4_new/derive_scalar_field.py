"""
Вывод выражения для скалярного поля на метрике де Ситтера.
Плоские координаты де Ситтера, разложение по модам.
"""
import sympy as sp

# === Переменные ===
t, x, y, z = sp.symbols('t x y z', real=True)
H, m, xi = sp.symbols('H m xi', real=True, positive=True)
kx, ky, kz = sp.symbols('kx ky kz', real=True)
k2 = kx**2 + ky**2 + kz**2

# === Метрика де Ситтера в плоских координатах ===
# ds² = -dt² + e^(2Ht)(dx² + dy² + dz²)
# Метрический тензор: g_μν = diag(-1, e^(2Ht), e^(2Ht), e^(2Ht))
a = sp.exp(H * t)  # масштабный фактор
g00 = -1
g11 = a**2
g22 = a**2
g33 = a**2

# === Уравнение Клейна-Гордона ===
# (□ - m² - ξR)φ = 0
# □φ = (1/√|g|) ∂_μ(√|g| g^μν ∂_ν φ)

# √|g| = a³
sqrt_g = a**3

# Обратная метрика
g00_inv = -1
g11_inv = 1/a**2
g22_inv = 1/a**2
g33_inv = 1/a**2

# Ricci scalar для де Ситтера: R = 12H²
R = 12 * H**2

print("=" * 60)
print("Метрика де Ситтера (плоские координаты):")
print(f"  ds² = -dt² + e^(2Ht)(dx² + dy² + dz²)")
print(f"  a(t) = e^(Ht)")
print(f"  R = 12H²")
print()

# === Уравнение Клейна-Гордона ===
# □φ = -∂²φ/∂t² - 3H ∂φ/∂t + (1/a²)∇²φ
# (получено из □φ = (1/√|g|)∂_μ(√|g|g^μν∂_νφ))

print("=" * 60)
print("Уравнение Клейна-Гордона:")
print("  (□ - m² - ξR)φ = 0")
print()
print("  □φ = -∂²φ/∂t² - 3H ∂φ/∂t + e^(-2Ht)∇²φ")
print()
print("  Полное уравнение:")
print("  -∂²φ/∂t² - 3H ∂φ/∂t + e^(-2Ht)∇²φ - (m² + 12ξH²)φ = 0")
print()

# === Разложение по модам ===
# φ(t,x) = ∫ d³k [a_k u_k(t) e^(ik·x) + a_k† u_k*(t) e^(-ik·x)]
# u_k(t) удовлетворяет:
#   u_k'' + 3H u_k' + (k²e^(-2Ht) + m² + 12ξH²)u_k = 0

print("=" * 60)
print("Разложение по модам:")
print("  φ(t,x) = ∫ d³k [a_k u_k(t) e^(ik·x) + c.c.]")
print()
print("  Уравнение для моды u_k(t):")
print("  u_k'' + 3H u_k' + (k²e^(-2Ht) + m² + 12ξH²)u_k = 0")
print()

# === Конформное время ===
# η = -e^(-Ht)/H, dη = -dt/a
# ds² = a²(η)(-dη² + dx²)
# a(η) = -1/(Hη)

eta = sp.symbols('eta', real=True)
a_eta = -1/(H * eta)

print("=" * 60)
print("Конформное время:")
print("  η = -e^(-Ht)/H")
print("  a(η) = -1/(Hη)")
print("  ds² = a²(η)(-dη² + dx²)")
print()

# === Уравнение в конформном времени ===
# Для φ = a^(-1)χ:
# χ'' + (k² + a²m² + 6ξHa)χ = 0
# где ' — производная по η

print("=" * 60)
print("Преобразование φ = a^(-1)χ:")
print("  χ'' + (k² + a²m² + 6ξHa)χ = 0")
print()

# === Конформный случай ξ = 1/6 ===
# a²m² + 6ξHa = a²m² + Ha² = a²(m² + H²)
# Если m = 0, ξ = 1/6 (конформное связывание): χ'' + k²χ = 0

print("=" * 60)
print("СЛУЧАЙ 1: Конформное связывание (ξ = 1/6, m = 0)")
print("  χ'' + k²χ = 0")
print("  χ_k(η) = (1/√(2k)) e^(-ikη)")
print("  φ_k(η) = a^(-1)χ_k = -Hη/√(2k) e^(-ikη)")
print()

# === Общий случай ===
# χ'' + (k² + ν² - 1/4)χ = 0, где ν² = 9/4 - (m² + 12ξH²)/H²
# Решение: χ_k(η) = √(-η) [C₁ H^(1)_ν(-kη) + C₂ H^(2)_ν(-kη)]

nu_sq = sp.Rational(9, 4) - (m**2 + 12*xi*H**2)/H**2
nu = sp.sqrt(nu_sq)

print("=" * 60)
print("СЛУЧАЙ 2: Общий случай (m ≠ 0 или ξ ≠ 1/6)")
print()
print("  ν² = 9/4 - (m² + 12ξH²)/H²")
print()
print("  χ_k(η) = √(-η) [C₁ H^(1)_ν(-kη) + C₂ H^(2)_ν(-kη)]")
print()
print("  φ_k(η) = a^(-1)χ_k = -Hη √(-η) [C₁ H^(1)_ν(-kη) + C₂ H^(2)_ν(-kη)]")
print()

# === Bunch-Davies vacuum ===
# C₁ = 0, C₂ = √(π/4) e^(i(2ν+1)π/4)
# φ_k(η) = √(π/4) e^(i(2ν+1)π/4) (-Hη)^(3/2) H^(2)_ν(-kη)

print("=" * 60)
print("Вакуум Банча-Дейвиса (C₁ = 0):")
print()
print("  φ_k(η) = √(π/4) e^(i(2ν+1)π/4) (-Hη)^(3/2) H^(2)_ν(-kη)")
print()
print("  где ν = √(9/4 - m²/H² - 12ξ)")
print()

# === Предельный переход H → 0 ===
print("=" * 60)
print("ПРЕДЕЛЬНЫЙ ПЕРЕХОД H → 0")
print("=" * 60)
print()

# Для конформного случая:
# φ_k = -Hη/√(2k) e^(-ikη)
# η = -e^(-Ht)/H → -1/H (константа при H→0)
# Но это не совсем правильно — нужно аккуратно.

# В конформном времени: η = -e^(-Ht)/H
# При H→0: η → -1/H + t + O(H)
# Но масштабный фактор a = -1/(Hη) = e^(Ht) → 1

# Для χ'' + k²χ = 0:
# χ_k = (1/√(2k)) e^(-ikη)
# φ_k = a^(-1)χ_k = e^(-Ht) (1/√(2k)) e^(-ikη)

# При H→0: e^(-Ht) → 1, η → t (с точностью до константы)
# φ_k → (1/√(2k)) e^(-ikt) — плоская мода Минковского

print("Конформный случай (ξ=1/6, m=0):")
print()
print("  φ_k(η) = a^(-1)(1/√(2k)) e^(-ikη)")
print()
print("  При H→0:")
print("    a = e^(Ht) → 1")
print("    η = -e^(-Ht)/H → t (с точностью до аддитивной константы)")
print("    φ_k → (1/√(2k)) e^(-ikt)")
print()
print("  Это — плосковолновое решение уравнения Клейна-Гордона")
print("  в пространстве Минковского: (∂²_t + k²)φ_k = 0")
print()

# Для общего случая используем асимптотику функции Ханкеля
print("Общий случай:")
print()
print("  При H→0: ν → 3/2 (так как m²/H² → ∞, но ν² = 9/4 - m²/H² - 12ξ)")
print("  На самом деле, при H→0 нужно фиксировать m и смотреть на поведение.")
print()
print("  Для фиксированных m, ξ при H→0:")
print("    ν² = 9/4 - m²/H² - 12ξ → -∞")
print("    Это означает, что нужно переопределить ν.")
print()
print("  Альтернативный подход: переходим к обычному времени t.")
print()

# Переход к обычному времени t
# u_k'' + 3H u_k' + (k²e^(-2Ht) + m² + 12ξH²)u_k = 0
# При H→0: u_k'' + (k² + m²)u_k = 0
# u_k(t) = (1/√(2ω_k)) e^(-iω_k t), где ω_k = √(k² + m²)

omega_k = sp.sqrt(k2 + m**2)

print("  Уравнение для u_k(t) при H→0:")
print("    u_k'' + (k² + m²)u_k = 0")
print()
print("    u_k(t) = (1/√(2ω_k)) e^(-iω_k t)")
print("    где ω_k = √(k² + m²)")
print()
print("  Полное решение:")
print("    φ(t,x) = ∫ d³k [a_k (1/√(2ω_k)) e^(-iω_k t + ik·x) + c.c.]")
print()
print("  Это — стандартное разложение свободного скалярного поля")
print("  в пространстве Минковского.")
print()

