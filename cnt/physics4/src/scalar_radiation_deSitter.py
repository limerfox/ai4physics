"""
Вывод излучения от свободной скалярной частицы в пространстве-времени де Ситтера.

Ссылка: Akhmedov 2010 (arXiv:1006.3274)

Свободная частица движется по геодезической, создаёт скалярное поле φ,
удовлетворяющее уравнению Клейна-Гордона с источником. Излучение
характеризуется потоком энергии через бесконечно удалённую поверхность.
"""

import sympy as sp

# ============================================================
# 1. Параметры и переменные
# ============================================================
t, r, theta, phi_angle = sp.symbols('t r theta phi', real=True)
H, m, xi, g = sp.symbols('H m xi g', real=True, positive=True)
tau = sp.symbols('tau', real=True)  # собственное время частицы

print("=" * 70)
print("1. СВОБОДНАЯ СКАЛЯРНАЯ ЧАСТИЦА В ПРОСТРАНСТВЕ-ВРЕМЕНИ ДЕ СИТТЕРА")
print("=" * 70)
print()

# ============================================================
# 2. Метрика де Ситтера (плоские координаты)
# ============================================================
# ds^2 = dt^2 - e^(2Ht) (dx^2 + dy^2 + dz^2)
# В сферических координатах:
# ds^2 = dt^2 - e^(2Ht) (dr^2 + r^2 dΩ^2)

g_tt = sp.Integer(1)
g_rr = -sp.exp(2 * H * t)
g_tt_angle = -sp.exp(2 * H * t) * r**2
g_pp_angle = -sp.exp(2 * H * t) * r**2 * sp.sin(theta)**2

sqrt_neg_g = sp.exp(3 * H * t) * r**2 * sp.sin(theta)

print("Метрика де Ситтера (плоские координаты, сферические):")
print(f"  ds^2 = dt^2 - e^(2Ht)[dr^2 + r^2(dθ^2 + sin²θ dφ^2)]")
print(f"  √(-g) = {sqrt_neg_g}")
print()

# ============================================================
# 3. Ток свободной скалярной частицы
# ============================================================
# Свободная частица движется по геодезической.
# В плоских координатах частица, покоящаяся в начале:
#   z^μ(τ) = (τ, 0, 0, 0)
#
# Ток: J(x) = g ∫ dτ δ⁴(x - z(τ)) / √(-g)

print("=" * 70)
print("2. ТОК СВОБОДНОЙ СКАЛЯРНОЙ ЧАСТИЦЫ")
print("=" * 70)
print()

# Мировая линия частицы, покоящейся в начале координат:
# z(τ) = (τ, 0, 0, 0)
# Ток:
J_expr = g * sp.DiracDelta(t - tau) * sp.DiracDelta(r) * sp.DiracDelta(sp.cos(theta)) / sqrt_neg_g

print("Мировая линия (геодезическая, частица покоится в начале):")
print("  z^μ(τ) = (τ, 0, 0, 0)")
print()
print("Ток:")
print("  J(x) = g ∫ dτ δ⁴(x - z(τ)) / √(-g)")
print()
print("Для частицы в начале координат:")
print("  J(x) = g · δ(t) · δ(r) / (e^(3Ht) · r² · sinθ)")
print()

# ============================================================
# 4. Уравнение Клейна-Гордона
# ============================================================
# (□ - m² - ξR)φ = J
#
# Даламбертиан в сферических координатах де Ситтера:
# □φ = ∂_t²φ + 3H∂_tφ - e^(-2Ht)[∂_r²φ + (2/r)∂_rφ + (1/r²)Δ_Ωφ]
# где Δ_Ω — угловая часть лапласиана

print("=" * 70)
print("3. УРАВНЕНИЕ КЛЕЙНА-ГОРДОНА")
print("=" * 70)
print()

R_scalar = 12 * H**2

print(f"Скалярная кривизна: R = 12H²")
print()
print("Даламбертиан в сферических координатах:")
print("  □φ = ∂_t²φ + 3H·∂_tφ - e^(-2Ht)·[∂_r²φ + (2/r)∂_rφ + (1/r²)Δ_Ωφ]")
print()
print("Уравнение Клейна-Гордона:")
print("  (□ - m² - ξR)φ = J")
print()
print("  ∂_t²φ + 3H·∂_tφ - e^(-2Ht)·[∂_r²φ + (2/r)∂_rφ + (1/r²)Δ_Ωφ]")
print("  - (m² + 12ξH²)φ = J")
print()

# ============================================================
# 5. Решение через функцию Грина
# ============================================================
print("=" * 70)
print("4. РЕШЕНИЕ ЧЕРЕЗ ФУНКЦИЮ ГРИНА")
print("=" * 70)
print()

print("Функция Грина G(x, x') удовлетворяет:")
print("  (□ - m² - ξR)G(x, x') = δ⁴(x - x') / √(-g)")
print()
print("Решение:")
print("  φ(x) = ∫ d⁴x' √(-g(x')) G(x, x') J(x')")
print()
print("Для точечного источника:")
print("  φ(x) = g · G(x, x₀)")
print()

# ============================================================
# 6. Энерго-импульсный тензор
# ============================================================
print("=" * 70)
print("5. ЭНЕРГО-ИМПУЛЬСНЫЙ ТЕНЗОР")
print("=" * 70)
print()

print("Энерго-импульсный тензор скалярного поля с неминимальной связью ξ:")
print()
print("  T_μν = ∂_μφ ∂_νφ - ½ g_μν (∂_αφ ∂^αφ - m²φ² - ξ(Rφ² - 6(∇φ)²))")
print()
print("Компоненты:")
print("  T_tt = (∂_tφ)² + ½(∂_iφ ∂^iφ + m²φ² + ξRφ²)")
print("  T_tr = -∂_tφ ∂_rφ")
print("  T_rr = (∂_rφ)² + ½((∂_tφ)² - e^(-2Ht)(∂_iφ ∂^iφ - m²φ² - ξRφ²))")
print()

# ============================================================
# 7. Мощность излучения
# ============================================================
print("=" * 70)
print("6. МОЩНОСТЬ ИЗЛУЧЕНИЯ")
print("=" * 70)
print()

print("Поток энергии через сферу радиуса r:")
print("  dP/dΩ = lim_{r→∞} r² · T^0r · √(-g) / r²")
print("        = lim_{r→∞} T^0r · √(-g)")
print()
print("В плоских координатах де Ситтера:")
print("  T^0r = g^{00}g^{rr}T_tr = -e^(-2Ht)·T_tr")
print("  T_tr = -∂_tφ ∂_rφ")
print()
print("  dP/dΩ = lim_{r→∞} e^(-2Ht) · ∂_tφ ∂_rφ · e^(3Ht) · r²")
print("         = lim_{r→∞} e^(Ht) · r² · ∂_tφ ∂_rφ")
print()

# Полная мощность
print("Полная мощность излучения:")
print("  P = ∮ dΩ · dP/dΩ")
print()

# ============================================================
# 8. Асимптотика поля на бесконечности
# ============================================================
print("=" * 70)
print("7. АСИМПТОТИКА ПОЛЯ НА БЕСКОНЕЧНОСТИ")
print("=" * 70)
print()

print("Для свободной частицы в де Ситтере поле на больших r:")
print()
print("  φ(t, r) ~ A(t) · e^(-iωt) · e^(-iωr*) / r")
print()
print("где r* — изоприближённая координата (tortoise coordinate):")
print("  dr*/dr = e^(-Ht) → r* ≈ r·e^(-Ht)")
print()
print("Для скалярного поля с m² + ξR < 5H²/4 (лёгкие поля):")
print("  Инфракрасное усиление приводит к ненулевому потоку на бесконечности.")
print()
print("Мощность излучения (общий вид):")
print("  P = (g² / 4π) · F(H, m, ξ)")
print()
print("где F — безразмерная функция, зависящая от H, m, ξ.")
print()

# ============================================================
# 9. Предельный переход H → 0
# ============================================================
print("=" * 70)
print("8. ПРЕДЕЛЬНЫЙ ПЕРЕХОД H → 0 (к пространству Минковского)")
